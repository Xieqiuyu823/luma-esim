    /** Decode the 3-byte GSMA/3GPP PLMN value, supplied as six hexadecimal digits. */
    fun fromOperatorId(operatorId: String): String? {
        if (operatorId.length != 6) return null
        val digits = operatorId.uppercase(Locale.ROOT)
        // Byte order: MCC2|MCC1, MNC3|MCC3, MNC2|MNC1. Only MNC3 may be F.
        if (digits.indices.any { index ->
                digits[index] !in '0'..'9' && !(index == 2 && digits[index] == 'F')
            }) return null
        val mcc = "${digits[1]}${digits[0]}${digits[3]}".toInt()
        // Unknown/absent metadata and international MCCs (e.g. 901) stay neutral.
        return countryByMcc[mcc]
    }

    fun drawable(countryCode: String?): Int =
        countryCode?.let { flagDrawables[it.uppercase(Locale.ROOT)] } ?: R.drawable.ic_luma_globe

